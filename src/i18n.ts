const dictionaries: Record<Lang, Record<string, string> | null> = { en: null, si, ta };

function detect(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'en' || saved === 'si' || saved === 'ta') return saved;
  } catch { /* storage blocked: fall through to browser language */ }
  const nav = (typeof navigator !== 'undefined' ? navigator.language : '').toLowerCase();
  if (nav.startsWith('si')) return 'si';
  if (nav.startsWith('ta')) return 'ta';
  return 'en';
}

let current: Lang = detect();
if (typeof document !== 'undefined') document.documentElement.lang = current;

export function getLang(): Lang {
  return current;
}

export function setLang(lang: Lang): void {
  current = lang;
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
  try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* preference just won't persist */ }
}

export function t(key: string, vars?: Record<string, string | number>): string {
  let out = dictionaries[current]?.[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
  }
  return out;
}
